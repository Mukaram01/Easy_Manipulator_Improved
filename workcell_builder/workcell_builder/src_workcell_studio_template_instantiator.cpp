std::string normalize_asset_id(const std::string & raw)
{
  std::string out;
  out.reserve(raw.size());
  for (const char c : raw) {
    if (std::isalnum(static_cast<unsigned char>(c))) {
      out.push_back(static_cast<char>(std::tolower(static_cast<unsigned char>(c))));
    }
  }
  return out;
}

bool contains_token(const std::string & haystack, const std::string & needle)
{
  return !needle.empty() && haystack.find(needle) != std::string::npos;
}

std::vector<std::string> alias_tokens_for_id(const std::string & raw_id)
{
  const std::string norm = normalize_asset_id(raw_id);
  std::vector<std::string> tokens;
  if (!norm.empty()) tokens.push_back(norm);
  if (contains_token(norm, "ur5")) {
    tokens.push_back("ur5");
    tokens.push_back("universalrobotur5");
    tokens.push_back("universalrobot");
  }
  if (contains_token(norm, "ur10")) tokens.push_back("ur10");
  if (contains_token(norm, "ur3")) tokens.push_back("ur3");
  if (contains_token(norm, "robotiq") || contains_token(norm, "2f85") || contains_token(norm, "2f")) {
    tokens.push_back("robotiq");
    tokens.push_back("2f85");
  }
  if (contains_token(norm, "airpick") || contains_token(norm, "suction") || contains_token(norm, "vacuum")) {
    tokens.push_back("airpick");
    tokens.push_back("suction");
    tokens.push_back("vacuum");
  }
  std::sort(tokens.begin(), tokens.end());
  tokens.erase(std::unique(tokens.begin(), tokens.end()), tokens.end());
  return tokens;
}

const AssetCandidate * map_selected_to_discovered(
  const std::string & selected_id, const std::vector<AssetCandidate> & candidates)
{
  const auto tokens = alias_tokens_for_id(selected_id);
  for (const auto & candidate : candidates) {
    const std::string key = normalize_asset_id(
      candidate.label + " " + candidate.description_package + " " + candidate.moveit_config_package);
    for (const auto & token : tokens) {
      if (contains_token(key, token)) {
        return &candidate;
      }
    }
  }
  return nullptr;
}

std::string sanitize(const std::string & raw)
{
  std::string out;
  for (const char c : raw) {
    if (std::isalnum(static_cast<unsigned char>(c)) || c == '_' || c == '-') out.push_back(static_cast<char>(std::tolower(static_cast<unsigned char>(c))));
    else if (std::isspace(static_cast<unsigned char>(c))) out.push_back('_');
  }
  return out.empty() ? "new_scene" : out;
}

void write_file(const fs::path & path, const std::string & text, WorkcellStudioTemplateInstantiationResult & r)
{
  fs::create_directories(path.parent_path());
  std::ofstream out(path.string());
  out << text;
  if (out.good()) r.created_files.push_back(path.string());
  else r.blockers.push_back("failed writing: " + path.string());
}

std::string generated_scene_xacro(const std::string & scene_name, const std::string & robot_id, const std::string & end_effector_id)
{
  return std::string(
    "<?xml version=\"1.0\"?>\n"
    "<robot xmlns:xacro=\"http://www.ros.org/wiki/xacro\" name=\"") + scene_name + "\">\n"
    "  <!-- Generated by Workcell Studio: minimal RViz truth preview scene -->\n"
    "  <link name=\"world\"/>\n"
    "\n"
    "  <!-- robot_visual_placeholder_due_to_missing_robot_xacro -->\n"
    "  <link name=\"robot_visual_placeholder_due_to_missing_robot_xacro\">\n"
    "    <visual><geometry><box size=\"0.30 0.20 0.50\"/></geometry><material name=\"blue\"><color rgba=\"0.2 0.4 0.9 1.0\"/></material></visual>\n"
    "  </link>\n"
    "  <joint name=\"world_to_robot_visual_placeholder\" type=\"fixed\">\n"
    "    <parent link=\"world\"/>\n"
    "    <child link=\"robot_visual_placeholder_due_to_missing_robot_xacro\"/>\n"
    "    <origin xyz=\"0 0 0\" rpy=\"0 0 0\"/>\n"
    "  </joint>\n"
    "\n"
    "  <!-- selected_robot_metadata: " + robot_id + " -->\n"
    "  <!-- selected_end_effector_metadata: " + end_effector_id + " -->\n"
    "  <!-- missing end-effector xacro -> placeholder visual only -->\n"
    "\n"
    "  <link name=\"support_surface\">\n"
    "    <visual><geometry><box size=\"1.20 0.80 0.04\"/></geometry><material name=\"gray\"><color rgba=\"0.5 0.5 0.5 1.0\"/></material></visual>\n"
    "  </link>\n"
    "  <joint name=\"world_to_support_surface\" type=\"fixed\">\n"
    "    <parent link=\"world\"/>\n"
    "    <child link=\"support_surface\"/>\n"
    "    <origin xyz=\"0.6 0 0.4\" rpy=\"0 0 0\"/>\n"
    "  </joint>\n"
    "</robot>\n";
}



std::string to_json_string_array(const std::vector<std::string> & values)
{
  std::ostringstream out;
  out << "[";
  for (std::size_t i = 0; i < values.size(); ++i) {
    if (i != 0) out << ", ";
    out << "\"" << values[i] << "\"";
  }
  out << "]";
  return out.str();
}

std::string generated_demo_launch()
{
  return
    "from launch import LaunchDescription\n"
    "from launch.actions import DeclareLaunchArgument\n"
    "from launch.conditions import IfCondition\n"
    "from launch.substitutions import Command, LaunchConfiguration, PathJoinSubstitution\n"
    "from launch_ros.actions import Node\n"
    "from launch_ros.substitutions import FindPackageShare\n\n"
    "\n"
    "def generate_launch_description():\n"
    "    use_fake_hardware = LaunchConfiguration('use_fake_hardware')\n"
    "    launch_rviz = LaunchConfiguration('launch_rviz')\n"
    "    urdf_xacro = PathJoinSubstitution([FindPackageShare(LaunchConfiguration('scene_pkg')), 'urdf', 'scene.urdf.xacro'])\n"
    "    robot_description = {'robot_description': Command(['xacro ', urdf_xacro, ' use_fake_hardware:=', use_fake_hardware])}\n"
    "    rsp = Node(package='robot_state_publisher', executable='robot_state_publisher', parameters=[robot_description])\n"
    "    rviz = Node(package='rviz2', executable='rviz2', condition=IfCondition(launch_rviz), arguments=['-d', PathJoinSubstitution([FindPackageShare(LaunchConfiguration('scene_pkg')), 'launch', 'demo.rviz'])], parameters=[robot_description])\n"
    "    return LaunchDescription([\n"
    "        DeclareLaunchArgument('scene_pkg', default_value='scene_name'),\n"
    "        DeclareLaunchArgument('use_fake_hardware', default_value='true'),\n"
    "        DeclareLaunchArgument('launch_rviz', default_value='true'),\n"
    "        rsp,\n"
    "        rviz,\n"
    "    ])\n";
}

